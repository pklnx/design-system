// Tests of the asset index project/design-system.json (design-system #24).
//
// The index is maintained by hand (no script writes it). Its `assetGroups` list every asset
// of the claude.ai design system and feed the Pages "Assets" page (scripts/build_site.mjs).
// The `blob` ids are opaque ids from the claude.ai asset upload, not content hashes, so they
// cannot be recomputed here; the test checks their shape and uniqueness only. The recorded
// `size` is the file's byte size and is checked against the file on disk.
//
// Coverage rule (what must be indexed): every file that lies directly in a group directory
// `project/assets/<Group>/` is indexed, except these explicit exclusions:
//   - README.md: the group's notes, shown on the Assets page, not an asset;
//   - the product social images `<product>-social.{svg,png}` in Social/: product assets,
//     generated by build_assets.py and render_pngs.mjs, tested by product-logos.test.mjs and
//     not uploaded to the claude.ai design system (see Social/README.md);
//   - subdirectories of a group (today only `Logos/products/`): generated, with their own
//     manifest, tested by product-logos.test.mjs.
// Any other file that is not indexed fails the test.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const ASSETS = path.join(ROOT, 'project/assets');
const INDEX = JSON.parse(readFileSync(path.join(ROOT, 'project/design-system.json'), 'utf8'));

const PRODUCTS = ['mail-archive', 'paperless-go'];
const NOT_INDEXED = new Set([
  'README.md',
  ...PRODUCTS.flatMap((p) => ['svg', 'png'].map((ext) => `${p}-social.${ext}`)),
]);
const TYPES = { '.svg': 'image/svg+xml', '.png': 'image/png' };

const dirs = (dir) => readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();
const assetFiles = (group) => readdirSync(path.join(ASSETS, group), { withFileTypes: true })
  .filter((e) => e.isFile() && !NOT_INDEXED.has(e.name)).map((e) => e.name).sort();

test('the index groups are exactly the directories of project/assets', () => {
  assert.deepEqual([...INDEX.groups].sort(), dirs(ASSETS));
  assert.deepEqual(Object.keys(INDEX.assetGroups).sort(), dirs(ASSETS));
});

for (const group of INDEX.groups) {
  const g = INDEX.assetGroups[group];

  test(`${group}: every asset file is indexed`, () => {
    assert.deepEqual(Object.keys(g.files).sort(), assetFiles(group));
  });

  test(`${group}: the order lists each indexed file exactly once`, () => {
    assert.deepEqual([...g.order].sort(), Object.keys(g.files).sort());
  });

  test(`${group}: size equals the byte size of the file`, () => {
    for (const [name, rec] of Object.entries(g.files)) {
      assert.equal(rec.size, statSync(path.join(ASSETS, group, name)).size, `${group}/${name}`);
    }
  });

  test(`${group}: name and type match the file`, () => {
    for (const [name, rec] of Object.entries(g.files)) {
      assert.equal(rec.name, name);
      assert.equal(rec.type, TYPES[path.extname(name)], `${group}/${name}`);
    }
  });
}

test('the excluded product social images exist and are not indexed', () => {
  for (const name of NOT_INDEXED) {
    if (name === 'README.md') continue;
    assert.ok(statSync(path.join(ASSETS, 'Social', name)).isFile(), name);
    assert.equal(name in INDEX.assetGroups.Social.files, false, name);
  }
});

test('blob ids are 32 hex characters and unique across the index', () => {
  const seen = new Map();
  for (const group of INDEX.groups) {
    for (const [name, rec] of Object.entries(INDEX.assetGroups[group].files)) {
      assert.match(rec.blob, /^[0-9a-f]{32}$/, `${group}/${name}`);
      assert.equal(seen.has(rec.blob), false, `${group}/${name} repeats the blob of ${seen.get(rec.blob)}`);
      seen.set(rec.blob, `${group}/${name}`);
    }
  }
});
